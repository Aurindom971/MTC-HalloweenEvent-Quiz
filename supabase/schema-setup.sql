begin;

create extension if not exists pgcrypto with schema extensions;

-- ----------------------------------------------------------------------------
-- 1. Round 1 Tables: registrations, questions, team_answers
-- ----------------------------------------------------------------------------

create table if not exists public.registrations (
  id bigint generated by default as identity primary key,
  full_name text not null,
  student_id text not null unique,
  phone text not null,
  email text not null unique,
  course text not null,
  academic_year smallint not null default 1,
  semester smallint,
  team_size smallint not null default 1,
  member2_name text,
  member2_phone text,
  member2_email text,
  registration_code text not null unique,
  created_at timestamptz not null default now()
);

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  seal integer not null,
  question_index integer not null,
  type text not null,
  prompt text not null,
  code text,
  options jsonb,
  correct_answer text not null,
  hint text,
  jumpscare jsonb,
  created_at timestamptz not null default now(),
  unique (seal, question_index)
);

create table if not exists public.team_answers (
  id bigint generated by default as identity primary key,
  registration_id bigint not null references public.registrations(id) on delete cascade unique,
  answers jsonb not null default '{}'::jsonb,
  submitted boolean not null default false,
  updated_at timestamptz not null default now()
);

create index if not exists team_answers_registration_id_idx on public.team_answers (registration_id);

alter table public.registrations enable row level security;
alter table public.questions enable row level security;
alter table public.team_answers enable row level security;

grant all on table public.registrations, public.questions, public.team_answers to service_role;
grant select on table public.registrations to anon, authenticated;
grant select on table public.questions to anon, authenticated;
grant all on table public.team_answers to anon, authenticated;

drop policy if exists "Allow public select registrations" on public.registrations;
create policy "Allow public select registrations" on public.registrations for select to anon, authenticated using (true);

drop policy if exists "Allow public select questions" on public.questions;
create policy "Allow public select questions" on public.questions for select to anon, authenticated using (true);

drop policy if exists "Allow public all team_answers" on public.team_answers;
create policy "Allow public all team_answers" on public.team_answers for all to anon, authenticated using (true) with check (true);

-- ----------------------------------------------------------------------------
-- 2. Round 2 Tables: r2_teams, r2_config, r2_hosts, r2_host_sessions
-- ----------------------------------------------------------------------------

create table if not exists public.r2_teams (
  key        text primary key check (key ~ '^[a-z0-9-]{1,120}$'),
  name       text not null check (char_length(btrim(name)) between 2 and 40),
  owner      text not null,
  data       jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.r2_config (
  id            text primary key,
  delay_minutes numeric check (delay_minutes >= 0 and delay_minutes <= 600),
  updated_at    timestamptz not null default now()
);
insert into public.r2_config (id) values ('event') on conflict (id) do nothing;

create table if not exists public.r2_hosts (
  email     text primary key,
  pass_hash text not null
);

create table if not exists public.r2_host_sessions (
  token_hash text primary key,
  email      text not null references public.r2_hosts (email) on delete cascade,
  expires_at timestamptz not null
);

alter table public.r2_teams         enable row level security;
alter table public.r2_config        enable row level security;
alter table public.r2_hosts         enable row level security;
alter table public.r2_host_sessions enable row level security;

revoke all on public.r2_teams, public.r2_config, public.r2_hosts, public.r2_host_sessions from anon, authenticated;
grant select on public.r2_teams, public.r2_config to anon, authenticated;
grant all on public.r2_teams, public.r2_config, public.r2_hosts, public.r2_host_sessions to service_role;

drop policy if exists "r2 teams are readable" on public.r2_teams;
create policy "r2 teams are readable" on public.r2_teams for select to anon, authenticated using (true);

drop policy if exists "r2 config is readable" on public.r2_config;
create policy "r2 config is readable" on public.r2_config for select to anon, authenticated using (true);

-- ----------------------------------------------------------------------------
-- 3. Round 2 Helper & RPC Functions
-- ----------------------------------------------------------------------------

create or replace function public.r2_hash(p_secret text) returns text
language sql immutable set search_path = '' as $$
  select encode(extensions.digest(p_secret, 'sha256'), 'hex')
$$;

create or replace function public.r2_host_email(p_token text) returns text
language sql stable security definer set search_path = '' as $$
  select s.email from public.r2_host_sessions s
  where s.token_hash = public.r2_hash(coalesce(p_token, '')) and s.expires_at > now()
$$;

create or replace function public.r2_require_host(p_token text) returns void
language plpgsql stable security definer set search_path = '' as $$
begin
  if public.r2_host_email(p_token) is null then
    raise exception 'Only the host can do that.' using errcode = '42501';
  end if;
end $$;

create or replace function public.r2_now_ms() returns bigint
language sql stable set search_path = '' as $$
  select (extract(epoch from now()) * 1000)::bigint
$$;

create or replace function public.r2_hello(p_device text, p_host text default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
begin
  if p_device is null or char_length(p_device) not between 20 and 100 then
    raise exception 'Bad device token.' using errcode = '22023';
  end if;
  return jsonb_build_object('owner', public.r2_hash(p_device), 'host', public.r2_host_email(p_host));
end $$;

create or replace function public.r2_register(p_device text, p_key text, p_name text, p_meta jsonb default '{}'::jsonb) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  meta jsonb := coalesce(p_meta, '{}'::jsonb);
begin
  if p_device is null or char_length(p_device) not between 20 and 100 then
    raise exception 'Bad device token.' using errcode = '22023';
  end if;
  if jsonb_typeof(meta) <> 'object'
     or exists (select 1 from jsonb_object_keys(meta) k where k not in ('leader', 'members'))
     or octet_length(meta::text) > 8000 then
    raise exception 'Bad team details.' using errcode = '22023';
  end if;
  insert into public.r2_teams (key, name, owner, data)
  values (p_key, btrim(p_name), public.r2_hash(p_device), meta)
  on conflict (key) do nothing;
  return found;
end $$;

create or replace function public.r2_save(p_device text, p_key text, p_patch jsonb) returns boolean
language plpgsql security definer set search_path = '' as $$
declare
  patch jsonb := coalesce(p_patch, '{}'::jsonb) - 'updatedAt';
begin
  if jsonb_typeof(patch) <> 'object'
     or exists (select 1 from jsonb_object_keys(patch) k where k not in (
          'stage', 'charId', 'problem', 'hex', 'hexAt', 'unlockAt', 'twist', 'twistText', 'twistExtra',
          'eggs', 'submissionUrl', 'repoUrl', 'zipUrl', 'zipName', 'zipSize', 'zipCloudUrl', 'submittedAt',
          'leader', 'members'))
     or octet_length(patch::text) > 16000 then
    raise exception 'Bad progress update.' using errcode = '22023';
  end if;
  update public.r2_teams
     set data = data || patch || jsonb_build_object('updatedAt', public.r2_now_ms()),
         updated_at = now()
   where key = p_key and owner = public.r2_hash(coalesce(p_device, ''));
  return found;
end $$;

create or replace function public.r2_host_login(p_email text, p_password text) returns text
language plpgsql security definer set search_path = '' as $$
declare
  h text;
  token text;
begin
  select pass_hash into h from public.r2_hosts where email = lower(btrim(p_email));
  if h is null or extensions.crypt(coalesce(p_password, ''), h) <> h then
    return null;
  end if;
  delete from public.r2_host_sessions where expires_at < now();
  token := encode(extensions.gen_random_bytes(24), 'hex');
  insert into public.r2_host_sessions (token_hash, email, expires_at)
  values (public.r2_hash(token), lower(btrim(p_email)), now() + interval '24 hours');
  return token;
end $$;

create or replace function public.r2_host_logout(p_token text) returns void
language sql security definer set search_path = '' as $$
  delete from public.r2_host_sessions where token_hash = public.r2_hash(coalesce(p_token, ''))
$$;

create or replace function public.r2_host_set_delay(p_token text, p_minutes numeric) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform public.r2_require_host(p_token);
  update public.r2_config set delay_minutes = p_minutes, updated_at = now() where id = 'event';
end $$;

create or replace function public.r2_host_wipe(p_token text) returns void
language plpgsql security definer set search_path = '' as $$
begin
  perform public.r2_require_host(p_token);
  delete from public.r2_teams where true;
end $$;

revoke execute on function
  public.r2_hash(text), public.r2_host_email(text), public.r2_require_host(text), public.r2_now_ms(),
  public.r2_hello(text, text), public.r2_register(text, text, text, jsonb), public.r2_save(text, text, jsonb),
  public.r2_host_login(text, text), public.r2_host_logout(text),
  public.r2_host_set_delay(text, numeric), public.r2_host_wipe(text)
  from public, anon, authenticated;

grant execute on function
  public.r2_hello(text, text), public.r2_register(text, text, text, jsonb), public.r2_save(text, text, jsonb),
  public.r2_host_login(text, text), public.r2_host_logout(text),
  public.r2_host_set_delay(text, numeric), public.r2_host_wipe(text)
  to anon, authenticated;

